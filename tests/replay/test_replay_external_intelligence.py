"""Phase 2 finalization, P2-16: LUMEN's opinions are exogenous input.

Found during the final Phase 2 audit, and confirmed by reproduction before
anything was changed.

LUMEN reads the information environment through an intelligence provider --
Claude, by configuration -- and publishes an ``AGENT_OPINION`` that carries
consensus weight 0.5. Nothing in a recording lets replay recompute what a
language model said, and calling the model again would produce a different
answer (and cost money, and need a network, in the middle of what is supposed
to be a hermetic reproduction).

Before this fix, replay did neither: LUMEN's loop is driven only by the live
``apps.orchestrator.__main__`` process, so it never ran during replay, and
``AGENT_OPINION`` is not in ``MARKET_INPUT_TYPES``, so the recorded opinion
was never replayed either. A session in which LUMEN moved consensus therefore
replayed WITHOUT that input -- and reported verified fidelity while doing it.

The contract now:

* Externally-produced opinions (``EXTERNAL_INTELLIGENCE_SOURCES``) are
  replayed as recorded inputs, exactly like a recorded book snapshot.
* Opinions derived deterministically from market data -- TIDAL, NORO, ZEPHR --
  are still RECOMPUTED. Replaying those would defeat the point of replay: a
  change to an agent would stop showing up as a different answer.
* Dropping external intelligence is possible, and is reported as
  ``UNVERIFIED_EXTERNAL_INTELLIGENCE`` rather than presented as exact.
"""

